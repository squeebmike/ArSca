import assert from 'node:assert/strict';
import {secretLairPrices,withSecretLairPrices} from '../scripts/secret-lair-prices.mjs';
import {marketplaceReferenceHtml} from '../scripts/catalog-inventory.mjs';
const card={scryfallId:'printing-1',tcgPlayerId:'123',name:'Exact printing'};
const drop={id:'price-test',cards:[card]};
const memory=new Map(),tasks=[];
const env={LBA_KV:{get:async key=>memory.get(key)||null,put:async(key,value)=>memory.set(key,JSON.parse(value))}};
let calls=0;
const options={fetcher:async(url,opts)=>{
 calls++;assert.equal(url,'https://api.scryfall.com/cards/collection');
 assert.deepEqual(JSON.parse(opts.body).identifiers,[{id:'printing-1'}]);
 return {ok:true,json:async()=>({data:[{id:'printing-1',tcgplayer_id:123,prices:{usd:'12.34',usd_foil:'23.45'}},{id:'unrequested',tcgplayer_id:123,prices:{usd:'999'}}]})};
}};
const ctx={waitUntil:p=>tasks.push(p)};
assert.deepEqual(await secretLairPrices(env,ctx,drop,options),[],'cold render never blocks on marketplace fetch');
await Promise.all(tasks);
const rows=await secretLairPrices(env,ctx,drop,options);
assert.equal(rows.length,1);assert.equal(calls,1);
const enriched=withSecretLairPrices(drop,rows);
assert.equal(enriched.cards[0].prices.usd,'12.34');assert.equal(card.prices,undefined,'static source data is unchanged');
const html=marketplaceReferenceHtml(enriched.cards[0],String);
assert.ok(html.includes('Nonfoil $12.34 USD')&&html.includes('Foil $23.45 USD')&&html.includes('via Scryfall')&&html.includes('checked'));
assert.equal(withSecretLairPrices(drop,[{...rows[0],tcgPlayerId:'different'}]).cards[0].prices,undefined);
for(const v of [null,undefined,0,-5,'NaN','Infinity',true,'<script>'])assert.ok(marketplaceReferenceHtml({prices:{usd:v}},String).includes('unavailable'));
const saved=memory.get('public-catalog:secret-lair-prices-v1:price-test');saved.at=Date.now()-7*60*60*1000;
const failures=[];const badCtx={waitUntil:p=>failures.push(p)};
const failure={fetcher:async()=>{calls++;throw Error('offline');}};
assert.deepEqual(await secretLairPrices(env,badCtx,drop,failure),[],'expired price not displayed as current');
await Promise.all(failures);
const before=calls;
for(let n=0;n<20;n++)await secretLairPrices(env,badCtx,drop,failure);
await Promise.all(failures);assert.equal(calls,before,'outage backoff prevents repeated upstream price requests');
console.log('Secret Lair exact-ID prices, nonblocking refresh, expiry and outage protection passed');
