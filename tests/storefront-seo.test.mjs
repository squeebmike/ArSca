import assert from 'node:assert/strict';
import {productFacts,productCondition,renderShopPreview,storeOrganization,productIdentity,storePolicyHtml} from '../scripts/storefront-seo.mjs';
const esc=s=>String(s).replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const item={id:'abc',name:'Batman <special>',price:6.99,condition:'Near Mint',category:'Comics',comic:{publisher:'DC',seriesName:'Batman',number:'25',coverArtists:['Nick Dragotta'],writers:['Scott Snyder']}};
const facts=productFacts(item);
assert.ok(facts.some(f=>f.name==='Writer'&&f.value==='Scott Snyder'));
assert.ok(facts.some(f=>f.name==='Issue number'&&f.value==='25'));
assert.ok(!productFacts({}).length);
assert.equal(productCondition('10'),undefined,'a grade is not a new/used condition');
assert.equal(productCondition('New'),'https://schema.org/NewCondition');
assert.equal(productCondition('Near Mint'),'https://schema.org/UsedCondition');
for(const condition of ['NM','NM/MT','LP','MP','HP','VF/NM','VG'])assert.equal(productCondition(condition),'https://schema.org/UsedCondition');
assert.equal(productCondition('PSA 10'),undefined);
const html=renderShopPreview(Array.from({length:30},(_,i)=>({...item,id:String(i)})),esc,()=> 'batman');
assert.equal((html.match(/<article>/g)||[]).length,24,'bounded HTML preview');
assert.match(html,/href="\/item\/0\/batman"/);
assert.match(html,/Batman &lt;special&gt;/);
assert.match(html,/\$6\.99 USD · In stock/);
assert.equal(renderShopPreview([],esc,()=>''),'');
const pending=renderShopPreview([{...item,price:0}],esc,()=> 'batman');
assert.ok(pending.includes('Price to be confirmed'));
assert.ok(!pending.includes('$0.00'),'an unpriced item is not advertised as free');
assert.ok(!('address' in storeOrganization));assert.ok(!('openingHours' in storeOrganization));
assert.equal(storeOrganization.hasMerchantReturnPolicy.merchantReturnLink,'https://www.themanapocket.com/terms-and-conditions');
assert.ok(!('merchantReturnDays' in storeOrganization.hasMerchantReturnPolicy),'do not change purchase-date terms into an invented delivery-date window');
assert.ok(!('shippingDetails' in storeOrganization),'live carrier quotes are not a fixed shipping price');
assert.equal(productIdentity(item).brand.name,'DC');
assert.equal(productIdentity({categorySlug:'pokemon'}).brand.name,'Pokémon');
assert.deepEqual(productIdentity({}),{},'unknown brands and identifiers stay unknown');
for(const [code,field] of [['036000291452','gtin12'],['4006381333931','gtin13'],['96385074','gtin8'],['00036000291452','gtin14']])assert.equal(productIdentity({gtinCandidates:[code]})[field],code);
assert.deepEqual(productIdentity({gtinCandidates:['036000291453','75960621582900621','store-sku-123']}),{},'invalid checksums, comic supplements and store SKUs must not become GTINs');
assert.equal(productIdentity({supplierUpc:'036000291452',mpn:'Manufacturer-part'}).mpn,'Manufacturer-part');
assert.ok(storePolicyHtml().includes('/terms-and-conditions'));
assert.ok(!('review' in productIdentity(item))&&!('aggregateRating' in productIdentity(item)));
console.log('Public product facts, safe preview HTML, condition and identity checks passed');
