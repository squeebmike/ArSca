import assert from 'node:assert/strict';
import {licensedSportsSets} from '../scripts/licensed-sports-seed.mjs';
import {licensedSportsPublicationProblems as check} from '../scripts/licensed-sports-policy.mjs';
const set=licensedSportsSets[0];
assert.deepEqual(check(set),[]);
assert.equal(set.cards.length,250);
assert.deepEqual(new Set(set.cards.map(c=>c.cardNumber)),new Set(Array.from({length:250},(_,i)=>String(i+1))));
assert.equal(set.cards.filter(c=>c.printedSection==='Base Set - Young Guns').length,50);
assert.equal(set.sections.length,92);
assert.equal(set.sections.reduce((n,g)=>n+g.cards.length,0),4168);
const checklist=set.cards.find(c=>c.cardNumber==='200');
assert.equal(checklist.checklistCard,true);
assert.deepEqual(checklist.subjects.map(s=>[s.name,s.team]),[['Nikita Kucherov','Tampa Bay Lightning'],['William Nylander','Toronto Maple Leafs']]);
const clear=set.sections.find(g=>g.name==='Clear Cut Parallel');
assert.equal(clear.cards.length,200);assert.notEqual(clear.cards[0].id,set.cards[0].id);
assert.equal(set.sections.flatMap(g=>g.cards).filter(c=>/Parallel/i.test(c.printedSection)).length,3386);
for(const patch of [{reviewed:false},{licensed:false},{sourceSha256:''},{sourceUrl:'https://example.com/fake'},{cardCount:249},{sport:'unreviewed-sport'}])assert.ok(check({...set,...patch}).length);
for(const patch of [{verified:false},{releaseYear:2023},{licensors:['NHLPA']},{sourceUrl:'https://example.com/license'}])assert.ok(check({...set,licensingEvidence:{...set.licensingEvidence,...patch}}).includes('league_and_player_licensing_review_required'));
assert.ok(check({...set,cards:[set.cards[0],set.cards[0]],cardCount:2}).includes('duplicate_or_invalid_card_route'));
console.log('Licensed sports foundation: primary licensing gates, 250 base including Young Guns, 4,168 distinct non-base rows, printed teams and route separation passed');

for(const release of licensedSportsSets)assert.deepEqual(check(release),[],release.id);
