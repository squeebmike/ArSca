teams.append('Homestead')
team_re=re.compile(r'^(.*?)\s+('+'|'.join(re.escape(t) for t in sorted(set(teams),key=len,reverse=True))+r')[\u00ae\u2122]?(?:\s+(.*))?$',re.I)
root=Path('../outputs/checklist-expansion-2026-10-21')
specs={'2024-topps-cosmic-chrome-baseball':('',200,'INSERT'),'2024-topps-stadium-club-baseball':('',300,'BASE SET CHROME VARIATION'),'2022-topps-cosmic-chrome':('',200,'INSERT'),'2022-topps-stadium-club-chrome':('',400,'INSERT'),'2021-bowman-draft-baseball':('BD-',200,'AUTOGRAPH')}
sets=[];groups=[]
def card(line,id,section,prefix):
 line=line.replace("Encarnacion-StrandCincinnati","Encarnacion-Strand Cincinnati").replace("Encarnacion-StrandMinnesota","Encarnacion-Strand Minnesota")
 m=re.match('^('+re.escape(prefix)+r'[A-Z0-9-]+)\s+(.+)$',line)
