"""Import two reviewed, complete sections from the exact 2023 Topps Chrome PDF."""
import ast, hashlib, json, re, sys
from pathlib import Path
root=Path(sys.argv[1]) if len(sys.argv)>1 else Path('../outputs/baseball-checklists-2023-up')
tree=ast.parse(Path(__file__).with_name('import-2023-baseball.py').read_text(encoding='utf8'))
teams=next(ast.literal_eval(n.value) for n in tree.body if isinstance(n,ast.Assign) and any(isinstance(t,ast.Name) and t.id=='teams' for t in n.targets))
team_re=re.compile(r'^(.*?)\s+('+'|'.join(re.escape(t) for t in sorted(teams,key=len,reverse=True))+r')[®™]?(?:\s+(.*))?$')
text=(root/'2023-topps-chrome.txt').read_text(encoding='utf8')
sections=[]
for ident,title,end,prefix,count,kind in [('ultra-violet-all-stars','ULTRA VIOLET ALL STARS','TOPPS CHROME TITANS','UV-',15,'Inserts'),('rookie-autographs','ROOKIE AUTOGRAPHS','1988 TOPPS BASEBALL AUTOGRAPHS','RA-',129,'Autographs')]:
    block=text.split(title+'\n',1)[1].split(end,1)[0]
    cards=[]
    for line in block.strip().splitlines():
        match=re.fullmatch(r'('+re.escape(prefix)+r'[A-Z0-9]+)\s+(.+)',line.strip())
        if not match: raise ValueError(('Unexpected row',line))
        number,rest=match.groups(); subject=team_re.fullmatch(rest)
        if not subject: raise ValueError(('Unknown subject/team',line))
        player,team,note=subject.groups()
        cards.append({'id':'2023-topps-chrome-'+number.lower(),'cardNumber':number,'player':player,'team':team,'section':title.title(),'variant':'Base','subjects':[{'name':player,'team':team,**({'note':note} if note else {})}]})
    assert len(cards)==count and len({c['id'] for c in cards})==count
    if prefix=='UV-': assert {c['cardNumber'] for c in cards}=={'UV-'+str(i) for i in range(1,16)}
    sections.append({'id':ident,'name':title.title(),'kind':kind,'cards':cards})
data={'setId':'2023-topps-chrome','sourceUrl':'https://cdn.shopify.com/s/files/1/0662/9749/5709/files/MLB2326-2023ToppsChromeBaseballChecklist.pdf','sourceSha256':hashlib.sha256((root/'2023-topps-chrome.pdf').read_bytes()).hexdigest(),'sections':sections}
Path(__file__).with_name('baseball-sections.mjs').write_text('// Reviewed official PDF sections; generated by import-chrome-sections.py.\nexport const baseballSections = '+json.dumps([data],ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf8',newline='\n')
print(json.dumps([{'section':s['name'],'cards':len(s['cards'])} for s in sections]))
