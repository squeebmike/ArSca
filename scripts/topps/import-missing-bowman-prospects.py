"""Recover separately numbered prospect blocks from saved publisher PDFs.

Run from the repository root after the source audit has saved sports-source-files.json.
Every source hash, row, printed prefix, count and contiguous range must reconcile.
Unknown teams remain empty when the publisher does not print a team column.
"""
import ast
import hashlib
import json
import re
from pathlib import Path

sources = {s['id']: s for s in json.loads(Path('../outputs/sports-source-files.json').read_text(encoding='utf-8'))}
tree = ast.parse(Path('scripts/topps/import-2023-baseball.py').read_text(encoding='utf-8'))
teams = next(ast.literal_eval(n.value) for n in tree.body if isinstance(n, ast.Assign)
             and any(isinstance(t, ast.Name) and t.id == 'teams' for t in n.targets))
teams += ['Athletics', 'Cleveland Indians']  # Preserve the printed release-year names.
# PDF text can join the player's surname to the known printed team column.
team_re = re.compile(r'^(.*?)\s*(' + '|'.join(re.escape(t) for t in sorted(teams, key=len, reverse=True))
                     + r')[®™]?(?:\s+(.*))?$', re.I)
specs = {
    '2023-bowman': [('PAPER PROSPECTS', 'paper-prospects', 'Paper Prospects', 'BP-', 1, 150),
                    ('CHROME PROSPECTS', 'chrome-prospects', 'Chrome Prospects', 'BCP-', 1, 150)],
    '2023-bowman-chrome': [('BOWMAN CHROME PROSPECTS', 'chrome-prospects', 'Chrome Prospects', 'BCP-', 151, 250)],
    '2025-bowman-baseball': [('PAPER PROSPECTS', 'paper-prospects', 'Paper Prospects', 'BP-', 1, 150),
                             ('CHROME PROSPECTS I', 'chrome-prospects', 'Chrome Prospects', 'BCP-', 1, 150)],
    '2025-bowman-draft-baseball': [('CHROME BASE CARDS', 'chrome-draft-picks', 'Chrome Draft Picks', 'BDC-', 1, 200)],
    '2021-bowman-draft-baseball': [('CHROME BASE CARDS I', 'chrome-draft-picks', 'Chrome Draft Picks', 'BDC-', 1, 200)],
}
output = []
for set_id, blocks in specs.items():
    source = sources[set_id]
    pdf = Path(source['file'])
    assert hashlib.sha256(pdf.read_bytes()).hexdigest() == source['hash'], set_id
    lines = [line.strip() for line in pdf.with_suffix('.txt').read_text(encoding='utf-8-sig').splitlines()]
    sections = []
    for heading, section_id, name, prefix, first, last in blocks:
        assert lines.count(heading) == 1, (set_id, heading)
        cards = []
        for line in lines[lines.index(heading) + 1:]:
            if not line:
                continue
            row = re.fullmatch('(' + re.escape(prefix) + r'\d+)\s+(.+)', line)
            if not row:
                break
            number, text = row.groups()
            if set_id == '2025-bowman-draft-baseball':
                player, team, note = text, '', None
            else:
                match = team_re.fullmatch(text)
                assert match, (set_id, line)
                player, printed_team, note = match.groups()
                team = next(t for t in teams if t.lower() == printed_team.lower())
            assert player and not any(c in player for c in '®™�'), (set_id, line)
            cards.append({'id': set_id + '-' + number.lower(), 'cardNumber': number,
                          'player': player, 'team': team, 'section': name, 'variant': 'Base',
                          'subjects': [{'name': player, 'team': team, **({'note': note} if note else {})}]})
        assert len(cards) == last - first + 1, (set_id, name, len(cards))
        assert {c['cardNumber'] for c in cards} == {prefix + str(n) for n in range(first, last + 1)}, (set_id, name)
        sections.append({'id': section_id, 'name': name, 'kind': 'Prospects', 'cards': cards})
    output.append({'setId': set_id, 'sourceUrl': source['sourceUrl'], 'sourceSha256': source['hash'], 'sections': sections})

Path('scripts/topps/bowman-prospect-sections.mjs').write_text(
    '// Separately numbered, hash-verified publisher prospect blocks. Generated by import-missing-bowman-prospects.py.\n'
    'export const bowmanProspectSections=' + json.dumps(output, ensure_ascii=False, separators=(',', ':')) + ';\n',
    encoding='utf-8', newline='\n')
print(json.dumps({'sets': len(output), 'sections': sum(len(s['sections']) for s in output),
                  'cards': sum(len(g['cards']) for s in output for g in s['sections'])}))
